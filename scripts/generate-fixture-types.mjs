import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, '..');
const fixtureSourcePath = path.join(rootDir, 'fixtures', 'test-base.js');
const fixtureTypesPath = path.join(rootDir, 'fixtures', 'test-base.d.ts');

const fixtureSource = fs.readFileSync(fixtureSourcePath, 'utf8');

const importRegex = /^import\s+\{\s*([A-Za-z_$][\w$]*)\s*\}\s+from\s+'(\.\.\/pages\/[^']+\.js)';/gm;
const importsByClass = new Map();
for (const match of fixtureSource.matchAll(importRegex)) {
  importsByClass.set(match[1], match[2]);
}

const fixtureRegex = /([A-Za-z_$][\w$]*)\s*:\s*async\s*\(\{\s*page\s*\},\s*use\s*\)\s*=>\s*\{[\s\S]*?await\s+use\(\s*new\s+([A-Za-z_$][\w$]*)\s*\(\s*page\s*\)\s*\);[\s\S]*?\}/g;
const fixtures = [];
for (const match of fixtureSource.matchAll(fixtureRegex)) {
  fixtures.push({ fixtureName: match[1], className: match[2] });
}

if (!fixtures.length) {
  throw new Error('No fixtures were found in fixtures/test-base.js.');
}

for (const fixture of fixtures) {
  if (!importsByClass.has(fixture.className)) {
    throw new Error(
      `Fixture "${fixture.fixtureName}" uses "${fixture.className}" but that class is not imported from ../pages/*.js.`
    );
  }
}

const importTypeLines = fixtures
  .map(({ className }) => className)
  .filter((className, index, all) => all.indexOf(className) === index)
  .map((className) => `import type { ${className} } from '${importsByClass.get(className)}';`)
  .join('\n');

const fixtureTypeLines = fixtures
  .map(({ fixtureName, className }) => `  ${fixtureName}: ${className};`)
  .join('\n');

const fileContent = `// This file is auto-generated by scripts/generate-fixture-types.mjs.
// Do not edit manually. Update fixtures/test-base.js and regenerate.

import type {
  PlaywrightTestArgs,
  PlaywrightTestOptions,
  PlaywrightWorkerArgs,
  PlaywrightWorkerOptions,
  TestType,
} from '@playwright/test';
import { expect as baseExpect } from '@playwright/test';
${importTypeLines}

type TestFixtures = {
${fixtureTypeLines}
};

type AllTestFixtures = PlaywrightTestArgs & PlaywrightTestOptions & TestFixtures;
type AllWorkerFixtures = PlaywrightWorkerArgs & PlaywrightWorkerOptions;

export const test: TestType<AllTestFixtures, AllWorkerFixtures>;
export const expect: typeof baseExpect;
`;

const previous = fs.existsSync(fixtureTypesPath) ? fs.readFileSync(fixtureTypesPath, 'utf8') : '';
if (previous !== fileContent) {
  fs.writeFileSync(fixtureTypesPath, fileContent, 'utf8');
  console.log('Updated fixtures/test-base.d.ts');
} else {
  console.log('fixtures/test-base.d.ts is up to date');
}
